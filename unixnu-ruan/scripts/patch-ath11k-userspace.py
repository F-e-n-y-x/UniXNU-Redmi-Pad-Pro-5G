#!/usr/bin/env python3
"""ruan's changes to drivers/Ath11kWifi's supplicant side (filipnavara/UniXNU-asteroids 9f07af3), applied to a fetched copy; idempotent.
Run by fetch-ath11k-wifi.sh and build-wifi-userspace.py.

usage: patch-ath11k-userspace.py ATH11K_DIR
1. driver_sheng.c: a scan-done event carries nl_scan_event = 1, as nl80211's NEW_SCAN_RESULTS does. Without it a scan the supplicant did
   not start (the board's self-test scan, wifid's through the module) left radio->external_scan_req_interface set for good, and every
   later scan of its own waited for it: "Delay radio work start until externally triggered scan completes", then "Pending scan
   scheduled - reject new request" for the rest of the boot; joins never scanned or associated (rbu181 wpa.log).
2. TKIP: CONFIG_NO_TKIP dropped and WPA_ALG_TKIP mapped to the module's cipher. rbu181's scan had networks with a TKIP group cipher
   ("TKIP as group cipher not supported in CONFIG_NO_TKIP=y build": WPA/WPA2 mixed-mode access points); ath11k and mac80211 (tkip.c,
   michael.c are in the module) handle it.
3. CONFIG_DEBUG_FILE=y: -f writes the supplicant's messages to a file (read over USB `cat`).
4. src/nw_mainline.c (kernel side): the time the module spends before a join or disconnect request reaches the supplicant (its
   interface close and reopen, nw_cfg80211_begin_attempt) goes to the log when it is over half a second (rbu183/185: 20 s between
   the request and the supplicant's SELECT_NETWORK). Only a log line.
5. src/nw_mainline.c + src/nw_cfg80211_control.c (kernel side): a join or disconnect request no longer closes and reopens the interface
   (nw_cfg80211_begin_attempt); it only checks the radio and opens the interface when it is down. The supplicant resets itself
   (REMOVE_NETWORK all, SELECT_NETWORK; DISCONNECT deauthenticates through it). The close and reopen cost 20 s per join (prior art:
   macOS/docs/research/wifi/join-prior-art.md): dev_open sets the 11d state PREPARING and the channel-list worker waits for it.
6. out/ath11k-src/mac.c (kernel side, regenerated by tools/prepare-ath11k.sh every build: build-ath11k-wifi.py runs this script after
   it): ath11k_mac_op_stop() ends a PREPARING 11d wait before cancel_work_sync(&ar->channel_update_work), not after, so a stop never
   waits out ATH11K_SCAN_TIMEOUT_HZ (20 s) for a worker that waits on that same completion.
"""
import sys
from pathlib import Path

root = Path(sys.argv[1])
driver = root / 'userspace/driver_sheng.c'
config = root / 'userspace/supplicant.config'
s = driver.read_text()
old = '    event.scan_info.aborted = view->header.status != NW_CONTROL_OK;\n'
new = old + '    event.scan_info.nl_scan_event = 1;   /* ruan: ends an external scan too (radio->external_scan_req_interface) */\n'
if new not in s:
    assert s.count(old) == 1, f'{driver}: scan-done anchor changed'
    s = s.replace(old, new)
old = '  case WPA_ALG_CCMP: cipher = RSN_CIPHER_SUITE_CCMP; break;\n'
new = old + '  case WPA_ALG_TKIP: cipher = RSN_CIPHER_SUITE_TKIP; break;   /* ruan: mixed-mode access points */\n'
if new not in s:
    assert s.count(old) == 1, f'{driver}: set_key anchor changed'
    s = s.replace(old, new)
driver.write_text(s)
c = config.read_text()
c = '\n'.join(line for line in c.splitlines() if line.strip() != 'CONFIG_NO_TKIP=y') + '\n'
if 'CONFIG_DEBUG_FILE=y' not in c:
    c += 'CONFIG_DEBUG_FILE=y\n'
config.write_text(c)
mainline = root / 'src/nw_mainline.c'
m = mainline.read_text()
old = '''    if (!result && pending.operation == NW_CONTROL_JOIN_REQUEST) {
      result = nw_cfg80211_begin_attempt();'''
new = '''    u64 attempt_started = lx_now_ms();   /* ruan: how long the interface cycle takes */
    if (!result && pending.operation == NW_CONTROL_JOIN_REQUEST) {
      result = nw_cfg80211_begin_attempt();'''
if 'attempt_started = lx_now_ms()' not in m:
    assert m.count(old) == 1, f'{mainline}: join anchor changed'
    m = m.replace(old, new)
old = '''    if (!result) result = nw_cfg80211_event_send(&b);
    if (!result) {'''
new = '''    if (!result) result = nw_cfg80211_event_send(&b);
    if (lx_now_ms() - attempt_started > 500)
      lx_log(4, "wifi: request %u to the supplicant took %llu ms: %d", pending.operation, (unsigned long long)(lx_now_ms() - attempt_started), result);
    if (!result) {'''
if new not in m:
    assert m.count(old) == 1, f'{mainline}: send anchor changed'
    m = m.replace(old, new)
old = '      result = nw_cfg80211_begin_attempt();\n'
new = '      result = nw_cfg80211_attempt_ready();   /* ruan: no interface close and reopen (20 s) */\n'
if new not in m:
    assert m.count(old) == 2, f'{mainline}: begin_attempt calls changed'
    m = m.replace(old, new)
mainline.write_text(m)
control = root / 'src/nw_cfg80211_control.c'
c = control.read_text()
old = 'int nw_cfg80211_set_power(int enabled) {\n'
new = '''/* ruan: what begin_attempt checks, without its interface close and reopen; opens the interface only when it is down. */
int nw_cfg80211_attempt_ready(void) {
  if (!owner || !primary) return -ENOTCONN;
  if (!radio_enabled) return -ERFKILL;
  if (netif_running(primary)) return 0;
  rtnl_lock(); int result = dev_open(primary, NULL); rtnl_unlock();
  return result;
}
''' + old
if 'nw_cfg80211_attempt_ready' not in c:
    assert c.count(old) == 1, f'{control}: set_power anchor changed'
    c = c.replace(old, new)
control.write_text(c)
header = root / 'src/nw_cfg80211_control.h'
h = header.read_text()
old = 'int nw_cfg80211_begin_attempt(void);\n'
if 'nw_cfg80211_attempt_ready' not in h:
    assert h.count(old) == 1, f'{header}: declaration anchor changed'
    h = h.replace(old, old + 'int nw_cfg80211_attempt_ready(void);\n')
header.write_text(h)
mac = root / 'out/ath11k-src/mac.c'
if mac.is_file():   # present after tools/prepare-ath11k.sh (build-ath11k-wifi.py calls this script then)
    a = mac.read_text()
    block = '''\tif (ar->state_11d == ATH11K_11D_PREPARING) {
\t\tar->state_11d = ATH11K_11D_IDLE;
\t\tcomplete(&ar->completed_11d_scan);
\t}
'''
    old = '\tcancel_delayed_work_sync(&ar->scan.timeout);\n\tcancel_work_sync(&ar->channel_update_work);\n'
    marked = '\t/* ruan: end the 11d wait first: channel_update_work may be waiting on it (20 s) */\n'
    if marked not in a:
        start = a.index('static void ath11k_mac_op_stop(')
        end = a.index('\n}\n', start)
        body = a[start:end]
        assert body.count(old) == 1 and body.count(block) == 1, f'{mac}: ath11k_mac_op_stop changed'
        body = body.replace(block, '', 1).replace(old, '\tcancel_delayed_work_sync(&ar->scan.timeout);\n' + marked + block +
                                                  '\tcancel_work_sync(&ar->channel_update_work);\n', 1)
        a = a[:start] + body + a[end:]
        mac.write_text(a)
print(f'{root}: userspace patched (scan-done ends external scans, TKIP, debug file)')
