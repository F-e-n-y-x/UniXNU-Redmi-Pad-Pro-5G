#!/usr/bin/env python3
"""UniXNU's Adreno740 driver for ruan's A710 (gpu 17/18, package/RuanAdrenoGlue.cpp) into build/ruan-adreno/libRuanAdreno.a,
force-loaded through CONFIG_XNU_EXTRA_LD_ARCHIVES (configs/ruan_defconfig). Modelled on UniXNU-sheng scripts/build-adreno740-kits.py
with the same compile recipes (the XNU records of bsd_init.c and IOPlatformExpert.cpp, its -W set).

What differs from sheng:
- kits/ArmSmmu4K and drivers/Adreno740 are copied to build/ruan-adreno/src and patches/adreno/*.patch applied there (SMR mask,
  one route through the board's accessors, no 4 MiB preemption records, NC table walk); the core tree stays unchanged.
- No GMU kit (ShengGmu*, Sm8550Platform), no command-db, no embedded firmware: RuanGpuPower.c boots the GMU and hands over the
  SQE it loaded. So NativeAdrenoService.cpp (ShengGmuColdStart), NativeAdrenoGmuConfig/GmuPlatform/KernelTime.cpp (ShengGmu.h)
  and NativeAdrenoClient.cpp / NativeAdrenoAccelerator.cpp (as sheng) are left out.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path('.').resolve()
DEVICE = Path(os.environ.get('UNIXNU_DEVICE', Path(__file__).resolve().parents[1]))
OUT = ROOT / 'build/ruan-adreno'
SRC = OUT / 'src'
RECORDS = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837'

shutil.rmtree(SRC, ignore_errors=True)
for relative in ('kits/ArmSmmu4K', 'drivers/Adreno740'):
    (SRC / relative).mkdir(parents=True)
    for path in (ROOT / relative).iterdir():
        if path.is_file() and path.suffix in ('.c', '.cpp', '.h', '.inc'):
            shutil.copyfile(path, SRC / relative / path.name)
for patch in sorted((DEVICE / 'patches/adreno').glob('*.patch')):
    subprocess.run(['patch', '-p1', '-s', '--forward', '-d', SRC, '-i', patch], check=True)

kit = SRC / 'kits/ArmSmmu4K'
driver = SRC / 'drivers/Adreno740'
SKIP = {'NativeAdrenoService.cpp', 'NativeAdrenoAccelerator.cpp', 'NativeAdrenoClient.cpp', 'NativeAdrenoGmuConfig.cpp',
        'NativeAdrenoGmuPlatform.cpp', 'NativeAdrenoKernelTime.cpp'}
sources = sorted(kit.glob('ArmSmmu4K*.c')) + [ROOT / 'kits/AdrenoPM4/AdrenoPM4.c']
sources += sorted(p for p in driver.glob('NativeAdreno*.cpp') if p.name not in SKIP)
sources += [DEVICE / 'package/RuanAdrenoGlue.cpp']

# gpu-zap=1 (package/RuanAdrenoGlue.cpp zapExit): the OEM-signed a710_zap.mbn as an array, generated here and never committed.
ZAP = Path(os.environ.get('FIRMWARE_DIR', os.environ.get('UNIXNU_WORK', '/root/unixnu-work') + '/firmware')) / 'a710_zap.mbn'
zap = ZAP.read_bytes()
assert zap[:4] == b'\x7fELF' and len(zap) == 12088, f'{ZAP}: not the 12088-byte a710_zap.mbn (RuanGmuBoard.h)'
(OUT / 'RuanZapFw.h').write_text('// Generated by scripts/build-ruan-adreno.py from a710_zap.mbn; never commit.\n#pragma once\n'
    'static const uint8_t ruan_zap_firmware[%d] = {%s};\n' % (len(zap), ','.join(str(b) for b in zap)))
build_id = hashlib.sha256(b''.join(p.name.encode() + p.read_bytes() for p in sources)).hexdigest()[:16]
records = {suffix: json.loads((RECORDS / name).read_text().strip().rstrip(','))
           for suffix, name in (('.c', 'bsd/DEVELOPMENT/bsd_init.o.json'), ('.cpp', 'iokit/DEVELOPMENT/IOPlatformExpert.cpo.json'))}
objects = []
for source in sources:
    recipe = records[source.suffix]
    obj = OUT / (source.stem + ('.kit.o' if source.suffix == '.c' else '.o'))
    command, arguments, i = [], recipe['arguments'], 0
    while i < len(arguments):
        value = arguments[i]
        if value == recipe['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(obj)]
            i += 1
        elif value in ('-MF', '-MJ', '-MT'):
            i += 1
        elif value == '-Xclang' and arguments[i + 1].startswith('-W'):
            i += 1
        elif not value.startswith('-W') and value not in ('-MD', '-MP'):
            command.append(value)
        i += 1
    command += ['-I', str(OUT), '-I', str(kit), '-I', str(driver), '-I', str(ROOT / 'kits/AdrenoPM4'), '-I', str(DEVICE / 'package'),
                '-I', str(ROOT / '.cache/xnu-work/osfmk'),
                '-DNATIVE_GPU_BUILD_ID=0x' + build_id + 'ULL',
                # ruan: A710 without CP preemption (no 4 MiB records), GPU SMMU walks non-cacheable as RuanGpuPower.c's contexts do.
                '-DNATIVE_ADRENO_NO_PREEMPT_RECORDS', '-DNATIVE_ADRENO_SMMU_COHERENT_WALK=0',
                # ruan: gpu-tlbiall=1/2 = CB TLBIALL / TLBIASID after every map/unmap of a process table (patches/adreno/0004).
                '-DARM_SMMU4K_TLB_EXPERIMENT',
                '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-Wno-incompatible-sysroot', '-Wno-c99-designator',
                '-Wno-reorder-init-list', '-Wno-deprecated-enum-enum-conversion', '-Wno-unnecessary-virtual-specifier']
    if source.name == 'NativeAdrenoUserClient.cpp':
        command += ['-include', str(DEVICE / 'package/RuanAdrenoXnu17.h')]
    if source.name == 'NativeAdrenoPublish.cpp':
        # ruan's own Metal-discovery stand-in (package/NativeAdrenoAccelerator.cpp, LegacyDisplayProbe.cpp) and RuanGpuPower.c's
        # blit fence counters already own these names; the driver's copies get ruan_adreno_driver_* names until step 5 (Metal)
        # replaces the stand-in. native_adreno_fences_detail stays: LegacyDisplayProbe.cpp only has a weak stub for it.
        command += ['-DAGXDeviceUserClient=RuanAdrenoDeviceUserClient',
                    '-Dnative_adreno_new_user_client=ruan_adreno_driver_new_user_client',
                    '-Dnative_adreno_note_property_read=ruan_adreno_driver_note_property_read',
                    '-Dnative_adreno_fences=ruan_adreno_driver_fences']
    result = subprocess.run(command, cwd=recipe['directory'], capture_output=True, text=True)
    if result.returncode:
        sys.exit(f'{source}:\n' + result.stderr[-4000:])
    objects.append(obj)

archive = OUT / 'libRuanAdreno.a'
archive.unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', archive, *objects], check=True)
defined = subprocess.run(['xcrun', 'nm', '-g', archive], capture_output=True, text=True, check=True).stdout
missing = [s for s in ('_ruan_adreno_glue_run', '_NativeAdrenoGpuContextBringupIo', '_native_adreno_publish', '_ArmSmmu4KAttachStreams',
                       '_AdrenoPM4Type7') if f' T {s}\n' not in defined]
if missing:
    sys.exit('libRuanAdreno.a lacks ' + ', '.join(missing))
# The kernel build does not track this archive (XNU_EXTRA_LD_ARCHIVES): drop the linked kernel when it changes.
digest = hashlib.sha256(archive.read_bytes()).hexdigest()
stamp = OUT / 'archive.sha256'
if not stamp.is_file() or stamp.read_text().strip() != digest:
    (RECORDS / 'mach.development.bcm2837.unstripped').unlink(missing_ok=True)
    stamp.write_text(digest + '\n')
print(f'PASS: libRuanAdreno.a {digest}, {len(objects)} objects')
