#!/usr/bin/env python3
"""Make the touch firmware headers the kernel build needs (never shipped: the firmware is Xiaomi's).

usage: tools/make-touch-fw.py <firmware dir>     e.g. the folder from `adb pull /vendor/firmware firmware`
Writes unixnu-ruan/.cache/hakios-fw/:
  hakios.novatek_ruan_fw.h      from novatek_ts_fw_boe.bin (ruan's NT36532 touch chip)
  hakios.focaltech_garnet_fw.h  a 1-byte stub: RuanTouch.c includes garnet's FocalTech path, which never runs on ruan
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'unixnu-ruan/.cache/hakios-fw'


def header(comment, guard, length_name, array_name, data):
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return (f'/* {comment} */\n#ifndef {guard}\n#define {guard}\n\n#define {length_name} {len(data)}\n\n'
            f'static const unsigned char {array_name}[{length_name}] = {{\n'
            + ''.join(f'\t{r},\n' for r in rows) + '};\n\n#endif\n')


if len(sys.argv) != 2:
    sys.exit(__doc__)
fw = Path(sys.argv[1]) / 'novatek_ts_fw_boe.bin'
if not fw.is_file():
    sys.exit(f'{fw} not found: pass the folder pulled from the tablet\'s /vendor/firmware')
data = fw.read_bytes()
if len(data) != 245760:
    sys.exit(f'{fw}: {len(data)} bytes, expected 245760 (wrong file?)')
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'hakios.novatek_ruan_fw.h').write_text(header(
    "Generated from ruan's /vendor/firmware/novatek_ts_fw_boe.bin (stock vendor_a). Do not edit; not for git.",
    '_RUAN_NOVATEK_FW_H', 'NOVATEK_RUAN_FW_LENGTH', 'novatek_ruan_fw', data))
(OUT / 'hakios.focaltech_garnet_fw.h').write_text(header(
    'Stub: garnet (FocalTech) firmware is not used on ruan. Generated by tools/make-touch-fw.py.',
    '_GARNET_FOCALTECH_FW_H', 'FOCALTECH_FW_LENGTH', 'focaltech_fw', b'\0'))
print(f'wrote {OUT}')
